// The server's allowlist (supabase/functions/_shared/allowlist.ts), built from the app's own prompts
// and schemas. scripts/server-allowlist.mts writes it; the test checks it's up to date.
import { createHash } from 'node:crypto'
import { TRACE_PROMPT } from '../island/prompt'
import { traceSchema } from '../island/tracer'
import { SYSTEM_PROMPT } from '../tutor/prompt'
import { replySchema } from '../tutor/tutor'

const sha256 = (text: string): string => createHash('sha256').update(text).digest('hex')

export function allowlistSource(): string {
  const entry = (hash: string, kind: string): string => `  '${hash}': '${kind}'`
  return `// Generated by app/scripts/server-allowlist.mts (npm run allowlist). Don't edit by hand.
// SHA-256 of each system prompt and reply schema the app sends, and which kind of request it is.

export type PromptKind = 'tutor' | 'trace'

export const SYSTEM_HASHES: Record<string, PromptKind> = {
${entry(sha256(SYSTEM_PROMPT), 'tutor')},
${entry(sha256(TRACE_PROMPT), 'trace')}
}

export const SCHEMA_HASHES: Record<string, PromptKind> = {
${entry(sha256(JSON.stringify(replySchema)), 'tutor')},
${entry(sha256(JSON.stringify(traceSchema)), 'trace')}
}
`
}
